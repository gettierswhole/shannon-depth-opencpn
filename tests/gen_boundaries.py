#!/usr/bin/env python3
"""Generate tests/boundary_data.h from tools/boundaries/boundaries.json."""
import json, sys
b = json.load(open(sys.argv[1]))
out = ["// Generated by tests/gen_boundaries.py. Do not edit by hand.", "#pragma once", "#include <vector>", "#include \"../src/core/depth_core.h\"", "namespace bdata {"]
out.append("inline std::vector<sd::Stretch> Stretches() {")
out.append("  std::vector<sd::Stretch> v(4);")
for i, sid in enumerate(["derg", "mid", "ree", "key"]):
    pts = ", ".join("{%r, %r}" % (a, c) for a, c in b[sid])
    out.append("  v[%d].id = \"%s\"; v[%d].boundary = {%s};" % (i, sid, i, pts))
out.append("  return v;\n}")
out.append("inline std::vector<sd::LockZone> Zones() {")
out.append("  return {")
for z in b["zones"]:
    out.append("    {%s, {%r, %r}, %r}," % (json.dumps(z["name"]), z["lat"], z["lon"], float(z["r"])))
out.append("  };\n}")
out.append("}  // namespace bdata")
print("\n".join(out))
