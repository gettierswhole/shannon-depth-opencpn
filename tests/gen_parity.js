#!/usr/bin/env node
// Generate tests/parity_vectors.h by running the Shannon Chart Depth page's
// own JavaScript (index.html) over a grid of gauge levels, charted depths and
// draughts. The C++ core must reproduce every result.
//
// Usage: node tests/gen_parity.js <index.html> > tests/parity_vectors.h
"use strict";
const fs = require("fs");
const vm = require("vm");

const html = fs.readFileSync(process.argv[2], "utf8");
function grab(re, what) {
  const m = html.match(re);
  if (!m) throw new Error("cannot find " + what);
  return m[0];
}
const src = [
  grab(/var FT = [^;]*POOLBEG_TO_MALIN = [^;]*;/, "constants"),
  grab(/var REACHES = \[[\s\S]*?\n  \];\n  REACHES\.forEach\([\s\S]*?\n  \}\);/, "REACHES"),
  grab(/function signed\(x, dp\) \{[^\n]*\}/, "signed"),
  grab(/function inSafe\(m\) \{[^\n]*\}/, "inSafe"),
  grab(/function inNear\(m\) \{[^\n]*\}/, "inNear"),
  grab(/function inUp\(m\) \{[^\n]*\}/, "inUp"),
  grab(/function ftInText\(n\) \{[\s\S]*?\n  \}/, "ftInText"),
  grab(/function signedIn\(n\) \{[^\n]*\}/, "signedIn"),
  grab(/function calc\(\) \{[\s\S]*?\n  \}/, "calc"),
].join("\n");

// Minimal stand-ins for the page's DOM and state: default datum settings,
// no manual reading, no lead-line checks.
const harness = `
var els = {};
function $(id) { return els[id] || (els[id] = { value: "", textContent: "", className: "" }); }
var CUR = null, LEVEL = null;
function reach() { return CUR; }
function datumOf(r) {
  if (r.feet == null || !r.cills.length) return r.osl ? r.osl.malin : null;
  return r.cills[0].malin + r.feet * FOOT;
}
function isOsl(r) { return !!r.osl && (r.feet == null || !r.cills.length); }
function uncOf(r) { return r.unc || 0.1; }
function correctionOf(r) { var d = datumOf(r); return d == null ? null : LEVEL - d; }
out.run = function (r, level, charted, draft) {
  CUR = r; LEVEL = level; els = {};
  $("charted").value = String(charted); $("draft").value = String(draft);
  calc();
  return { depth: $("depth").textContent, depthFt: $("depth-ft").textContent,
           clear: $("clear").textContent, clearFt: $("clear-ft").textContent };
};
out.REACHES = REACHES; out.datumOf = datumOf;
out.inSafe = inSafe; out.inUp = inUp; out.ftInText = ftInText; out.signedIn = signedIn;
`;
const out = {};
vm.runInNewContext(src + harness, { out, Math, String, isFinite, parseFloat });

const q = (s) => JSON.stringify(s);
const lines = [];
lines.push("// Generated by tests/gen_parity.js from the Shannon Chart Depth page.");
lines.push("// Do not edit by hand.");
lines.push("#pragma once");
lines.push("namespace parity {");

lines.push("struct StretchVec { const char* id; bool has_datum; double datum; double band; bool estimated; };");
lines.push("static const StretchVec kStretches[] = {");
for (const r of out.REACHES) {
  const d = out.datumOf(r);
  lines.push(`  {${q(r.id)}, ${d != null}, ${d == null ? 0 : d.toPrecision(17)}, ${r.unc}, ${!!r.osl && (r.feet == null || !r.cills.length)}},`);
}
lines.push("};");

lines.push("struct FmtVec { int n; const char* ftin; const char* signed_in; };");
lines.push("static const FmtVec kFormat[] = {");
for (let n = -40; n <= 40; n++) lines.push(`  {${n}, ${q(out.ftInText(n))}, ${q(out.signedIn(n))}},`);
lines.push("};");

lines.push("struct CorrVec { const char* id; double level; int inches; int band; };");
lines.push("struct CalcVec { const char* id; double level; double charted; double draught; const char* depth; const char* depth_ft; const char* clear; const char* clear_ft; };");
const corr = [], calc = [];
for (const r of out.REACHES) {
  const d = out.datumOf(r);
  if (d == null) continue;
  // Levels from 0.6 m below to 0.6 m above the datum in 7 mm steps, plus
  // values just either side of whole inches to test the rounding.
  const levels = [];
  for (let k = -86; k <= 86; k++) levels.push(d + k * 0.007);
  for (let k = -12; k <= 12; k++) { levels.push(d + k * 0.0254 + 1e-7); levels.push(d + k * 0.0254 - 1e-7); }
  for (const lv of levels) corr.push(`  {${q(r.id)}, ${lv.toPrecision(17)}, ${out.inSafe(lv - d)}, ${out.inUp(r.unc)}},`);
  for (const lv of [d - 0.31, d - 0.05, d, d + 0.12, d + 0.47])
    for (const ch of [0.9, 1.5, 2.1, 3.0])
      for (const dr of [0.9, 1.1, 1.3]) {
        const o = out.run(r, lv, ch, dr);
        calc.push(`  {${q(r.id)}, ${lv.toPrecision(17)}, ${ch}, ${dr}, ${q(o.depth)}, ${q(o.depthFt)}, ${q(o.clear)}, ${q(o.clearFt)}},`);
      }
}
lines.push("static const CorrVec kCorrections[] = {", ...corr, "};");
lines.push("static const CalcVec kCalcs[] = {", ...calc, "};");
lines.push("}  // namespace parity");
process.stdout.write(lines.join("\n") + "\n");
